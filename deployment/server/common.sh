#!/usr/bin/env bash

# Это библиотека функций, а не самостоятельный запускаемый скрипт.
# Серверные скрипты подключают её командой `. "$SCRIPT_DIR/common.sh"`.
# Команда `.`, также известная как `source`, определяет функции библиотеки в том
# же процессе Bash, поэтому вызывающий скрипт может использовать их напрямую.
# Здесь намеренно нет `set -euo pipefail`: режим выполнения выбирает каждый
# запускаемый скрипт до подключения библиотеки.

# Вывести ошибку деплоя и завершить текущий запускаемый скрипт.
# `$*` объединяет все аргументы функции в одну строку. `>&2` отправляет её в
# поток ошибок stderr. Благодаря этому stdout остаётся свободным для функций,
# значение которых вызывающий код получает через подстановку команд `$(...)`.
deployment_fail() {
    echo "ERROR: $*" >&2
    exit 1
}

# Прочитать одно значение из dotenv-файла, не выполняя его содержимое как Bash-код.
# Первый аргумент — искомый ключ, второй — путь к dotenv-файлу. Если ключ указан
# несколько раз, возвращается последнее значение. Дополнительные символы `=`
# внутри самого значения при этом сохраняются.
deployment_env_value() {
    local key="$1"
    local file="$2"

    # `awk -F=` использует `=` как разделитель полей. Для найденного ключа
    # `substr` берёт всё после первого `=`, а не только второе поле. Блок `END`
    # печатает последнее найденное значение. `tr` удаляет символ возврата каретки,
    # который остаётся у dotenv-файлов с Windows-окончаниями строк CRLF.
    awk -F= -v key="$key" '
        $1 == key {
            value = substr($0, index($0, "=") + 1)
        }
        END {
            print value
        }
    ' "$file" | tr -d '\r'
}

# Вернуть обязательное значение из dotenv-файла. Если оно пустое или содержит
# демонстрационную заглушку `change-me`, завершить деплой с ошибкой.
# Аргументы функции: ключ и путь к dotenv-файлу.
deployment_require_env() {
    local key="$1"
    local file="$2"
    local value

    # `$(...)` — подстановка команды: Bash записывает stdout вызванной функции
    # в переменную и автоматически удаляет завершающие переводы строки.
    value="$(deployment_env_value "$key" "$file")"

    # `[[ ... ]]` — условное выражение Bash. Команда после `||` выполняется только
    # при ложном условии, поэтому недопустимое значение останавливает скрипт.
    [[ -n "$value" && "$value" != change-me ]] || deployment_fail "Set non-placeholder '$key' in $file."

    # Здесь намеренно нет `\n`: вызывающий код обычно забирает точное значение
    # через `$(...)`, а не выводит его пользователю отдельной строкой.
    printf '%s' "$value"
}

# Вернуть необязательное значение из dotenv-файла или переданное значение по
# умолчанию. Аргументы: ключ, значение по умолчанию и путь к файлу.
# `${value:-$default_value}` выбирает значение по умолчанию, если файл вернул
# пустую строку.
deployment_optional_env() {
    local key="$1"
    local default_value="$2"
    local file="$3"
    local value

    value="$(deployment_env_value "$key" "$file")"
    printf '%s' "${value:-$default_value}"
}

# Заменить или добавить значение в серверный dotenv-файл, не подключая его как
# shell-код. Аргументы: ключ, новое значение и путь к файлу. Новое содержимое
# сначала записывается во временный файл, а затем заменяет исходный `.env`.
# Поэтому при ошибке генерации рабочий файл не останется записанным наполовину.
deployment_update_env_value() {
    local key="$1"
    local value="$2"
    local file="$3"
    local temporary_file

    # `mktemp` заменяет `XXXXXX` случайными символами и безопасно создаёт
    # уникальный файл рядом с исходным. Это позволяет завершить замену атомарно.
    temporary_file="$(mktemp "${file}.XXXXXX")"

    # Первая строка с ключом заменяется, а последующие дубликаты отбрасываются.
    # Если ключ не найден, блок `END` добавляет его после исходных строк.
    awk -v key="$key" -v value="$value" '
        index($0, key "=") == 1 {
            if (!updated) {
                print key "=" value
                updated = 1
            }
            next
        }
        {
            print
        }
        END {
            if (!updated) {
                print key "=" value
            }
        }
    ' "$file" > "$temporary_file"

    # Сохранить права исходного файла и заменить его одним перемещением.
    chmod --reference="$file" "$temporary_file"
    mv "$temporary_file" "$file"
}

# Проверить одно обычное DNS-имя или остановить деплой.
# Оператор Bash `=~` проверяет значение регулярным выражением. Разрешены буквы,
# цифры, точки и дефисы, но первый и последний символы должны быть буквами или
# цифрами. Так посторонний текст не попадёт в сгенерированную конфигурацию nginx.
deployment_validate_hostname() {
    local hostname="$1"

    [[ "$hostname" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]] || deployment_fail "Invalid hostname '$hostname'."
}

# Проверить список имён серверов nginx, разделённых запятыми или пробелами.
# `${1//,/ }` заменяет все запятые пробелами. Затем Bash разбивает результат по
# пробельным символам, а цикл проверяет каждое имя отдельно.
deployment_validate_server_names() {
    local server_names="$1"
    local name

    [[ -n "$server_names" ]] || deployment_fail "Server names are empty."

    for name in ${server_names//,/ }; do
        deployment_validate_hostname "$name"
    done
}

# Вернуть первое имя из списка, разделённого запятыми или пробелами.
# `set --` заменяет позиционные аргументы функции элементами разделённого списка;
# после этого в `$1` находится основное настроенное имя сервера.
deployment_first_server_name() {
    set -- ${1//,/ }
    printf '%s' "$1"
}

# Экранировать текст перед подстановкой в заменяющую часть выражения `sed`.
# Вызывающий код использует `|` как разделитель. Символы `\`, `&` и `|` имеют
# в заменяющей строке специальный смысл, поэтому `sed` добавляет перед каждым
# обратную косую черту и заставляет воспринимать его буквально.
deployment_escape_sed() {
    printf '%s' "$1" | sed 's/[\\&|]/\\&/g'
}
